import { describe, expect, it } from 'vitest';
import { isConversationalFollowUp } from '@/lib/rag/gap-filter';

/**
 * فلتر ضجيج الفجوات — على أمثلة الإنتاج الحقيقية.
 *
 * القائمة المستبعَدة أدناه منسوخة من جدول `knowledge_gaps` على
 * الإنتاج: متابعاتٌ محادثية سُجِّلت فجواتٍ فملأت قائمة المديرة بما
 * لا يُوثَّق. والممرَّرة أسئلةُ معرفةٍ حقيقية — بعضها قصير وبعضها
 * يشارك المتابعات لفظًا — ويجب ألّا يضيع منها شيء.
 */

describe('يستبعد المتابعات المحادثية', () => {
  const followUps = [
    'تاكد الان',
    'تأكد',
    'هل حصلت على الاجابه',
    'هل حصلت على الإجابة؟',
    'مكتوب بالمصدر 70% تاكد اكثر',
    'طيب كمل',
    'تمام شكرا',
    'هل انت متاكد',
    'كمل',
    'وضح اكثر',
  ];

  for (const text of followUps) {
    it(`«${text}» لا يُسجَّل فجوة`, () => {
      expect(isConversationalFollowUp(text)).toBe(true);
    });
  }
});

describe('يمرّر أسئلة المعرفة الحقيقية', () => {
  const realQuestions = [
    // قصير وحقيقي — القِصر وحده ليس ضجيجًا
    'كم مدة الاجازه؟',
    'الاستثمار',
    'انا ابي ادارة المشاريع',
    'شروط العامه لتوطين مهن ادارة المشاريع',
    'ماهي تعديلات ملخص نظام عمل',
    // يشارك المتابعات لفظ «تأكد» لكنه سؤال معرفة — الحدود تحميه
    'كيف أتأكد من استحقاق الإجازة؟',
    'ما إجراءات التحقق من الهوية؟',
    // «هل حصلت» عن واقعة لا عن إجابة المساعد
    'هل حصلت الموظفة على بدل السكن؟',
    // طويل مهما بدا شكله
    'طيب في حال كان الموظف على رأس العمل وطلب إجازة استثنائية فما الإجراء النظامي المتبع في ذلك؟',
  ];

  for (const text of realQuestions) {
    it(`«${text}» يمرّ`, () => {
      expect(isConversationalFollowUp(text)).toBe(false);
    });
  }
});
