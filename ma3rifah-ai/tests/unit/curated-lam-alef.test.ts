import { describe, expect, it } from 'vitest';
import {
  repairCuratedLamAlef,
  repairCorruptedNumerals,
  repairLamAlefOrder,
} from '@/lib/rag/extract';

/**
 * بقايا قلب لام-ألف — الصنف الذي لا تفصله قاعدة.
 *
 * وُجد في الإنتاج فعلًا: «الدليل الإجرائي لقرار توطين المهن الهندسية»
 * خرج ١٤ مقطعًا من ١٥ معطوبة، وفيها «لألجور» و«لالحتساب» — ولا
 * تمسّهما القاعدتان المُبرهَنتان لأن لا ألفين متتاليتين فيهما.
 *
 * والاختبار على نصوص الإنتاج نفسها لا على أمثلة مُخترعة: العيّنات
 * أدناه منسوخة من مقاطع معطوبة حقيقية.
 */

/** الخطّ الكامل كما يجري في الاستخراج */
function fullRepair(text: string): string {
  return repairCuratedLamAlef(repairCorruptedNumerals(repairLamAlefOrder(text)));
}

describe('عيّنات الإنتاج المعطوبة', () => {
  it('سطر الحدّ الأدنى للأجور — من دليل التوطين حرفيًا', () => {
    expect(fullRepair('الحد األدنى لألجور لالحتساب في نسبة التوطين')).toBe(
      'الحد الأدنى للأجور للاحتساب في نسبة التوطين',
    );
  });

  it('العطبان معًا: لام-ألف وألفاظ العدد في سطر واحد', () => {
    expect(fullRepair('خالل ثالثين يومًا من تاريخ اإلبالغ')).toBe(
      'خلال ثلاثين يومًا من تاريخ الإبلاغ',
    );
  });

  it('«وال يجوز إال بموافقة» — من نظام العمل حرفيًا', () => {
    expect(fullRepair('تسري األحكام الواردة في هذا النظام وال يجوز إال بموافقة')).toBe(
      'تسري الأحكام الواردة في هذا النظام ولا يجوز إلا بموافقة',
    );
  });
});

describe('الجذوع المُنسَّقة', () => {
  const cases: ReadonlyArray<readonly [string, string]> = [
    ['وتحدد الالئحة المواعيد', 'وتحدد اللائحة المواعيد'],
    ['بالالئحة التنفيذية', 'باللائحة التنفيذية'],
    ['خالل المدة النظامية', 'خلال المدة النظامية'],
    ['من خاللها', 'من خلالها'],
    ['هؤالء العاملون', 'هؤلاء العاملون'],
    ['أوالده القاصرون', 'أولاده القاصرون'],
    ['داخل البالد وخارجها', 'داخل البلاد وخارجها'],
    ['المستندات الالزمة', 'المستندات اللازمة'],
    ['الشهر الالحق', 'الشهر اللاحق'],
    ['لإلجراء المتبع', 'للإجراء المتبع'],
    ['لإلدارة المختصة', 'للإدارة المختصة'],
    ['لإلشراف على التنفيذ', 'للإشراف على التنفيذ'],
  ];

  for (const [corrupted, correct] of cases) {
    it(`«${corrupted}» ⇒ «${correct}»`, () => {
      expect(repairCuratedLamAlef(corrupted)).toBe(correct);
    });
  }
});

describe('«وال» قبل أفعال الأنظمة', () => {
  it('يصلح «وال يجوز» و«وال تزيد» و«وال سيما»', () => {
    expect(repairCuratedLamAlef('وال يجوز ذلك وال تزيد المدة وال سيما العمال')).toBe(
      'ولا يجوز ذلك ولا تزيد المدة ولا سيما العمال',
    );
  });

  it('لا يمسّ «وال» أمام كلمة ليست من القائمة — قد تكون «والٍ»', () => {
    const text = 'أميرٌ أو وال عادل';
    expect(repairCuratedLamAlef(text)).toBe(text);
  });

  it('لا يمسّ «الوالي» ولا «والي» — اللام موصولة فليست منفردة', () => {
    const text = 'والي المنطقة يجوز له';
    expect(repairCuratedLamAlef(text)).toBe(text);
  });
});

describe('الشواهد المضادّة — سليمٌ لا يُمَسّ', () => {
  const untouched = [
    // «الالتزام» و«الالتحاق» سليمتان — والجذعان «الالزم» و«الالحق»
    // المعطوبان لا يطابقانهما حرفيًا
    'الالتزام بالمواعيد شرط',
    'طلب الالتحاق بالدورة',
    // لام الجرّ على مصدرٍ مبدوءٍ بهمزة وصل — صورة سليمة تشبه المعطوب
    'لالتزامه بالعقد',
    // كلمات سليمة من عائلة الشكل نفسه
    'تلألأ النجم ولآلئ الخليج',
    'باهلل العظيم'.replace('هلل', 'لله'), // «بالله» — لامان متتاليتان سليمتان
    'خالد بن الوليد',
    'لألف سببٍ وسبب',
    'لألعاب القوى ميدان',
  ];

  for (const text of untouched) {
    it(`«${text}» يبقى كما هو`, () => {
      expect(repairCuratedLamAlef(text)).toBe(text);
    });
  }

  it('شاهد الإجراء الكامل: نصّ سليم يمرّ بالخطّ كله بلا تغيير', () => {
    const clean =
      'يلتزم صاحب العمل بالسلامة المهنية، ويجوز للوزارة خلال ثلاثين يومًا من الالتحاق مراجعة الالتزام.';
    expect(fullRepair(clean)).toBe(clean);
  });
});
