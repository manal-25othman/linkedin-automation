import { describe, expect, it } from 'vitest';
import { repairLamAlefOrder } from '@/lib/rag/extract';

/**
 * رباط لام-ألف المفكوك مقلوبًا.
 *
 * ملفٌ حقيقيّ من ستّ وأربعين صفحة خرج منه «الباب الأول» بصيغة «الباب
 * األول»: الألف قبل اللام. وفيه أربعمئة وثمانٍ وتسعون موضعًا كذلك،
 * ولا موضع واحد صحيح — فالعطل شاملٌ لا استثناء فيه.
 *
 * وأثره ليس تجميليًّا: «الأحكام» تُخزَّن «األحكام»، فلا يشبه متجهها
 * متجه السؤال المكتوب صحيحًا، فيقول المساعد «لم أجد» عن نصٍّ أمامه.
 *
 * ولا يُرى العطل في أي اختبار بناء أو نوع: النصّ سليم الترميز، ويبدو
 * للعين العابرة عربيًّا صحيحًا.
 */

describe('ألفان متتاليتان ثم لام — اللام كانت بينهما', () => {
  it('«األحكام» ⇒ «الأحكام»', () => {
    expect(repairLamAlefOrder('التعريفات / األحكام العامة')).toBe('التعريفات / الأحكام العامة');
  });

  it('«اإلدارة» ⇒ «الإدارة»', () => {
    expect(repairLamAlefOrder('اإلدارة')).toBe('الإدارة');
  });

  it('«اآلتية» ⇒ «الآتية»', () => {
    expect(repairLamAlefOrder('العبارات اآلتية')).toBe('العبارات الآتية');
  });

  it('«إال» ⇒ «إلا» — ألفان وإن لم تكن أولاهما ألف تعريف', () => {
    expect(repairLamAlefOrder('إال بإذن')).toBe('إلا بإذن');
  });

  it('«اال» في «الالتزام» تعود إلى موضعها', () => {
    expect(repairLamAlefOrder('اال')).toBe('الا');
  });
});

describe('كلمة «ال» منفردة — أداة التعريف لا تقوم وحدها', () => {
  it('«ال يجوز» ⇒ «لا يجوز»', () => {
    expect(repairLamAlefOrder('ال يجوز للعامل')).toBe('لا يجوز للعامل');
  });

  it('في أول النصّ وآخره', () => {
    expect(repairLamAlefOrder('ال')).toBe('لا');
    expect(repairLamAlefOrder('قال: ال.')).toBe('قال: لا.');
  });
});

/**
 * الضوابط السالبة — وهي أهمّ من الحالات الموجبة.
 *
 * القلب الأعمى يفسد أكثر ممّا يصلح: «سأل» تصير «سلأ» و«إلى» تصير
 * «لإى». فالقاعدة تُقاس بما تتركه لا بما تغيّره.
 */
describe('ما لا يجوز أن يُمَسّ', () => {
  it('«إلى» تبقى — ألف مهموزة ثم لام، ولا ألف ثانية', () => {
    expect(repairLamAlefOrder('يعود إلى العمل')).toBe('يعود إلى العمل');
  });

  it('«سأل» و«مسألة» تبقيان', () => {
    expect(repairLamAlefOrder('سأل عن مسألة')).toBe('سأل عن مسألة');
  });

  it('«خالد» و«مال» و«أعمال» تبقى — ألف ولام مشروعتان', () => {
    expect(repairLamAlefOrder('خالد أنفق مال أعمال')).toBe('خالد أنفق مال أعمال');
  });

  it('أداة التعريف الملتصقة تبقى', () => {
    expect(repairLamAlefOrder('الشركة والعامل')).toBe('الشركة والعامل');
  });

  it('نصّ سليم أصلًا لا يتغيّر', () => {
    const sound = 'المادة الأولى: لا يجوز إلا بإذن الإدارة الآتية';
    expect(repairLamAlefOrder(sound)).toBe(sound);
  });
});

describe('التطبيق مرّتين كالتطبيق مرّة', () => {
  it('لا يتأرجح النصّ بين صورتين', () => {
    // النصّ يمرّ بـ cleanText مرّتين (لكل صفحة ثم للمجموع)
    const raw = 'الباب األول: ال يجوز إال باألجر';
    const once = repairLamAlefOrder(raw);
    expect(repairLamAlefOrder(once)).toBe(once);
    expect(once).toBe('الباب الأول: لا يجوز إلا بالأجر');
  });
});
