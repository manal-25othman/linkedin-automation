import { describe, expect, it } from 'vitest';
import { cleanText, repairCorruptedNumerals, repairLamAlefOrder } from '@/lib/rag/extract';

/**
 * رباط لام-ألف المفكوك مقلوبًا.
 *
 * ملفٌ حقيقيّ من ستّ وأربعين صفحة خرج منه «الباب الأول» بصيغة «الباب
 * األول»: الألف قبل اللام. وفيه أربعمئة وثمانٍ وتسعون موضعًا كذلك،
 * ولا موضع واحد صحيح — فالعطل شاملٌ لا استثناء فيه.
 *
 * وأثره ليس تجميليًّا: «الأحكام» تُخزَّن «األحكام»، فلا يشبه متجهها
 * متجه السؤال المكتوب صحيحًا، فيقول المساعد «لم أجد» عن نصٍّ أمامه.
 *
 * ولا يُرى العطل في أي اختبار بناء أو نوع: النصّ سليم الترميز، ويبدو
 * للعين العابرة عربيًّا صحيحًا.
 */

describe('ألفان متتاليتان ثم لام — اللام كانت بينهما', () => {
  it('«األحكام» ⇒ «الأحكام»', () => {
    expect(repairLamAlefOrder('التعريفات / األحكام العامة')).toBe('التعريفات / الأحكام العامة');
  });

  it('«اإلدارة» ⇒ «الإدارة»', () => {
    expect(repairLamAlefOrder('اإلدارة')).toBe('الإدارة');
  });

  it('«اآلتية» ⇒ «الآتية»', () => {
    expect(repairLamAlefOrder('العبارات اآلتية')).toBe('العبارات الآتية');
  });

  it('«إال» ⇒ «إلا» — ألفان وإن لم تكن أولاهما ألف تعريف', () => {
    expect(repairLamAlefOrder('إال بإذن')).toBe('إلا بإذن');
  });

  it('«اال» في «الالتزام» تعود إلى موضعها', () => {
    expect(repairLamAlefOrder('اال')).toBe('الا');
  });
});

describe('كلمة «ال» منفردة — أداة التعريف لا تقوم وحدها', () => {
  it('«ال يجوز» ⇒ «لا يجوز»', () => {
    expect(repairLamAlefOrder('ال يجوز للعامل')).toBe('لا يجوز للعامل');
  });

  it('في أول النصّ وآخره', () => {
    expect(repairLamAlefOrder('ال')).toBe('لا');
    expect(repairLamAlefOrder('قال: ال.')).toBe('قال: لا.');
  });
});

/**
 * الضوابط السالبة — وهي أهمّ من الحالات الموجبة.
 *
 * القلب الأعمى يفسد أكثر ممّا يصلح: «سأل» تصير «سلأ» و«إلى» تصير
 * «لإى». فالقاعدة تُقاس بما تتركه لا بما تغيّره.
 */
describe('ما لا يجوز أن يُمَسّ', () => {
  it('«إلى» تبقى — ألف مهموزة ثم لام، ولا ألف ثانية', () => {
    expect(repairLamAlefOrder('يعود إلى العمل')).toBe('يعود إلى العمل');
  });

  it('«سأل» و«مسألة» تبقيان', () => {
    expect(repairLamAlefOrder('سأل عن مسألة')).toBe('سأل عن مسألة');
  });

  it('«خالد» و«مال» و«أعمال» تبقى — ألف ولام مشروعتان', () => {
    expect(repairLamAlefOrder('خالد أنفق مال أعمال')).toBe('خالد أنفق مال أعمال');
  });

  it('أداة التعريف الملتصقة تبقى', () => {
    expect(repairLamAlefOrder('الشركة والعامل')).toBe('الشركة والعامل');
  });

  it('نصّ سليم أصلًا لا يتغيّر', () => {
    const sound = 'المادة الأولى: لا يجوز إلا بإذن الإدارة الآتية';
    expect(repairLamAlefOrder(sound)).toBe(sound);
  });
});

/**
 * محارف الاتجاه غير المرئية.
 *
 * كانت مكتوبة في `cleanText` بذاتها لا بهروبها، وفيها محرف NUL. ومحرفٌ
 * غير مرئيّ في الشيفرة لا يُرى حين يضيع: يمرّ الملفّ في نقلٍ أو محرّرٍ
 * أو أداة تنسيق فيسقط، ولا يشكو مترجمٌ ولا مدقّق — ويبقى النصّ
 * المستخرَج محشوًّا بها فتفسد المطابقة والتقطيع.
 *
 * فكُتبت بالهروب، وهذا الحارس يثبت أن الهروب يكافئ الحرف.
 */
describe('كل محرف اتجاه غير مرئيّ ما زال يُزال', () => {
  const INVISIBLES = [
    0x0000, 0x200b, 0x200c, 0x200d, 0x200e, 0x200f, 0x202a, 0x202b, 0x202c, 0x202d, 0x202e, 0x2066,
    0x2067, 0x2068, 0x2069, 0xfeff,
  ];

  it.each(INVISIBLES)('U+%s يُزال', (code) => {
    expect(cleanText(`أ${String.fromCodePoint(code)}ب`)).toBe('أب');
  });

  it('النصّ العربيّ السليم لا يُمَسّ', () => {
    expect(cleanText('المادة الأولى')).toBe('المادة الأولى');
  });
});

describe('التطبيق مرّتين كالتطبيق مرّة', () => {
  it('لا يتأرجح النصّ بين صورتين', () => {
    // النصّ يمرّ بـ cleanText مرّتين (لكل صفحة ثم للمجموع)
    const raw = 'الباب األول: ال يجوز إال باألجر';
    const once = repairLamAlefOrder(raw);
    expect(repairLamAlefOrder(once)).toBe(once);
    expect(once).toBe('الباب الأول: لا يجوز إلا بالأجر');
  });
});

/**
 * ألفاظ العدد.
 *
 * ظهر في مستند حقيقي: «تُزاد إلى مدة لا تقل عن **ثالثين** يوما».
 *
 * والأثر لم يكن في الإجابة — النموذج قرأ «ثالثين» وكتب «ثلاثين»
 * صحيحة. بل في **طبقة التحقّق**: بحثت عن «30» في المصدر فلم تجدها،
 * فوضعت تحذيرًا على رقمٍ صحيح.
 *
 * والتحذير الكاذب أخطر من غيابه: يتعلّم المستخدم تجاهله، فيسقط حين
 * يكون صادقًا.
 */
describe('ألفاظ العدد المعطوبة', () => {
  it('«ثالثين» ⇒ «ثلاثين» — الحالة التي وقعت فعلًا', () => {
    expect(repairCorruptedNumerals('لا تقل عن ثالثين يوما')).toBe('لا تقل عن ثلاثين يوما');
  });

  it('«ثالثون» و«ثالثمائة» كذلك', () => {
    expect(repairCorruptedNumerals('ثالثون')).toBe('ثلاثون');
    expect(repairCorruptedNumerals('ثالثمائة ريال')).toBe('ثلاثمائة ريال');
  });

  /**
   * الضوابط السالبة — وهي سبب حصر القائمة.
   *
   * «ثالث» و«ثالثة» كلمتان صحيحتان من العائلة نفسها شكلًا. ولو
   * أُدرجتا لأفسد الإصلاحُ نصًّا سليمًا — وهو أسوأ من تركه معطوبًا،
   * لأن المعطوب يُرى والمفسَد لا يُرى.
   */
  it('«ثالث» و«ثالثة» لا تُمَسّان — وهما صحيحتان', () => {
    expect(repairCorruptedNumerals('الباب الثالث')).toBe('الباب الثالث');
    expect(repairCorruptedNumerals('المادة الثالثة')).toBe('المادة الثالثة');
    expect(repairCorruptedNumerals('الفصل الثالث والعشرون')).toBe('الفصل الثالث والعشرون');
  });

  it('«ثلاثين» السليمة تبقى كما هي', () => {
    expect(repairCorruptedNumerals('ثلاثين يوما')).toBe('ثلاثين يوما');
  });

  it('التطبيق مرّتين كالتطبيق مرّة', () => {
    const once = repairCorruptedNumerals('عن ثالثين يوما');
    expect(repairCorruptedNumerals(once)).toBe(once);
  });
});
