-- =====================================================================
-- الأسئلة التي فشل المساعد في إجابتها — مجموعة الاختبار الحقيقية
-- =====================================================================
-- كل «لم أجد» يُسجَّل فجوةً في knowledge_gaps مع عدد مرات السؤال.
-- فلا حاجة إلى تأليف أسئلة اختبار: الفشل الحقيقي مسجَّل هنا بالفعل.
-- =====================================================================
select
  g.question                                   as "السؤال",
  g.times_asked                                as "كم مرة سُئل",
  g.status                                     as "الحالة",
  to_char(g.last_asked_at, 'YYYY-MM-DD')       as "آخر مرة",
  c.name                                       as "الشركة"
from public.knowledge_gaps g
join public.companies c on c.id = g.company_id
order by g.times_asked desc, g.last_asked_at desc
limit 50;
