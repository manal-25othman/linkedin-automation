-- =====================================================================
-- أيّ المستندات فُهرست بنصّ معطوب وتحتاج إعادة معالجة
-- =====================================================================
-- إصلاح رباط لام-ألف (٢٥ أغسطس) يعمل وقت الفهرسة، لا بأثر رجعيّ.
-- فمستندٌ رُفع قبله لا تزال مقاطعه المخزّنة معطوبة («األحكام»، «إال»)
-- والبحث فيها — الدلاليّ واللفظيّ معًا — يفشل عن نصّ لا يشبه أي سؤال.
--
-- الكشف بقاعدة إملائية قاطعة: ألفان متتاليتان قبل لام ممتنعتان في
-- العربية، و«ال» كلمةً منفردة أصلها «لا» المقلوبة.
--
-- يقرأ ولا يكتب. وكل مستند عليه ⚠️ يُضغط له «إعادة المعالجة» من اللوحة.
-- =====================================================================
select
  d.name                                         as "المستند",
  d.status                                       as "الحالة",
  to_char(coalesce(d.processed_at, d.created_at), 'YYYY-MM-DD') as "آخر معالجة",
  count(*)                                       as "كل المقاطع",
  count(*) filter (where c.content ~ '[آأإا][آأإا]ل'
                      or c.content ~ '(^|[^ء-ي])ال($|[^ء-ي])')
                                                 as "مقاطع معطوبة",
  case when count(*) filter (where c.content ~ '[آأإا][آأإا]ل'
                                or c.content ~ '(^|[^ء-ي])ال($|[^ء-ي])') > 0
       then '⚠️ أعد معالجته' else '✅ سليم' end   as "القرار"
from public.document_chunks c
join public.documents d on d.id = c.document_id
group by d.id, d.name, d.status, d.processed_at, d.created_at
order by 5 desc;
