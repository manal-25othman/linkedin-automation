-- =====================================================================
-- فاحص عطب النصّ العربي في المقاطع المخزونة
-- =====================================================================
-- يُلصق في محرّر SQL على Supabase. يقرأ ولا يكتب.
--
-- ملفات PDF العربية تفكّ رباط لام-ألف مقلوبًا («الأحكام» تُخزَّن
-- «األحكام»)، فيحمل الفهرس كلماتٍ لا وجود لها ولا يطابقها سؤال —
-- والمساعد يقول «لم أجد» عن نصٍّ موجود.
--
-- أي مستند يظهر فيه عددٌ غير صفر: افتح لوحة التحكم ← المستندات ←
-- «إعادة المعالجة» له، ثم أعد هذا الفحص — المطلوب صفر في كل صفّ.
-- =====================================================================
select
  d.name                                       as "المستند",
  d.status                                     as "الحالة",
  to_char(max(c.created_at), 'YYYY-MM-DD')     as "آخر معالجة",
  count(*)                                     as "كل المقاطع",
  count(*) filter (where
       c.content ~ '[آأإا][آأإا]ل'
    or c.content ~ '(^|[^ء-ي])ال([^ء-ي]|$)'
    or c.content ~ 'خالل|الالئح|هؤالء|أوالد|البالد|الالزم|الالحق|إبالغ|لألجور|لالحتساب|لإلجراء|لإلدارة|لإلشراف|ثالثين|ثالثون'
  )                                            as "مقاطع معطوبة"
from public.document_chunks c
join public.documents d on d.id = c.document_id
group by d.id, d.name, d.status
order by 5 desc, d.name;
