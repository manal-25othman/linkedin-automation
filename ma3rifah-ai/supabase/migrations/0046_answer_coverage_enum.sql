-- =====================================================================
-- 0046 — حالتان ناقصتان في تصنيف الإجابة
--
-- `answer_status` يعرف حالتين فقط: أجابت أو لم تجد. وبينهما حالتان
-- تقعان كثيرًا ولا يسجّلهما شيء:
--
--   ١) **تغطية ناقصة** — السؤال من شقّين، والوثائق تغطّي شقًّا واحدًا.
--      تُسجَّل اليوم `ANSWERED`، فلا تصل إلى قائمة الفجوات أبدًا، ويبقى
--      الشقّ الثاني بلا توثيق إلى الأبد. وهذه أسوأ من `UNANSWERED`:
--      تلك على الأقل تُرى.
--
--   ٢) **سؤال يحتاج توضيحًا** — «كم مدة الإجازة؟» والوثائق تفرّق بين
--      فئات الموظفين. أي جواب واحد عنها خاطئ لبعض السائلين، والصواب
--      أن يُطلب التوضيح لا أن يُختار فرعٌ ضمنًا.
--
-- ولماذا هذا الترحيل وحده في ملفّه:
--
--   `alter type ... add value` لا تُستعمل قيمتُه داخل المعاملة نفسها
--   التي أضافته. ولوحة Supabase تنفّذ الملصوق معاملةً واحدة. فلو جاء
--   في ملفٍّ فيه جدولٌ أو دالّةٌ تذكر القيمة الجديدة لفشل الملف كلّه،
--   والفشل هنا يقع في منتصف ترحيل — وهو أسوأ موضع يقع فيه.
--
--   فالفصل ليس ترتيبًا بل شرطُ صحّة.
-- =====================================================================

alter type public.answer_status add value if not exists 'PARTIAL';
alter type public.answer_status add value if not exists 'NEEDS_CLARIFICATION';

-- لا شيء بعد هذا السطر عمدًا: القيمتان لا تُستعملان إلا بعد الالتزام.
