import { Circle, type LucideIcon } from 'lucide-react';

/**
 * اختيار أيقونة بترتيب العنصر في قائمته.
 *
 * المحتوى صار يُحرَّر من اللوحة، فعدد البطاقات لم يعد ثابتًا: تُضاف بطاقة
 * سادسة إلى خمس أيقونات فتنكسر الصفحة على `undefined`. وهذه الدالة تحسم
 * ذلك بلا شرط متكرّر في كل صفحة.
 *
 * ولا تدوير هنا: البطاقة الزائدة تأخذ أيقونة محايدة بدل أن تكرّر أيقونة
 * بطاقةٍ قبلها. لأن تكرار الأيقونة يوحي بعلاقة بين بطاقتين لا علاقة
 * بينهما، والشكل المحايد يُقرأ «لا أيقونة لهذه» — وهو الصدق.
 */
export function pickIcon(icons: LucideIcon[], index: number): LucideIcon {
  return icons[index] ?? Circle;
}
