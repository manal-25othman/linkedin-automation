/**
 * سجلّ نصوص الموقع القابلة للتحرير.
 *
 * كل نصّ هنا له مفتاح ثابت وقيمة افتراضية. القيمة الافتراضية هي ما يظهر
 * ما لم يُحرَّر، فالجدول في قاعدة البيانات يحمل **التجاوزات وحدها**.
 *
 * ولماذا سجلّ مسطّح لا شجرة متداخلة: المحرِّر يُبنى من هذا السجلّ آليًا،
 * والمسطّح يُعرض جدولًا ويُحرَّر حقلًا حقلًا بلا أن يفهم أحد بنية JSON.
 * والتداخل يشتري ترتيبًا نظريًا بثمن واجهة أصعب على من ستستعملها.
 *
 * وإضافة نصّ جديد إلى التحرير خطوتان: أضف مدخلًا هنا، واقرأه في الصفحة
 * عبر `text('المفتاح')`. لا تعديل في المحرِّر ولا في قاعدة البيانات.
 */

export interface SiteTextEntry {
  /** الصفحة التي يظهر فيها — للتجميع في المحرِّر */
  page: string;
  /** وصف مختصر يعرّف المحرِّرة بموضع النصّ */
  label: string;
  /** النصّ الأصلي — يظهر ما لم يُحرَّر */
  value: string;
  /** نصّ طويل يُحرَّر في مساحة متعددة الأسطر */
  multiline?: boolean;
  /** تلميح عن قيد أو أثر */
  hint?: string;
}

