/**
 * سجلّ محتوى الموقع القابل للتحرير.
 *
 * كل مدخل هنا له مفتاح ثابت وقيمة افتراضية. القيمة الافتراضية هي ما
 * يظهر ما لم يُحرَّر، فالجدول في قاعدة البيانات يحمل **التجاوزات وحدها**.
 *
 * ونوعان من المدخلات:
 *
 *   • `text`  — نصّ واحد: عنوان، فقرة، زر.
 *   • `list`  — قائمة عناصر متكرّرة: بطاقات، خطوات، أسئلة شائعة.
 *
 * ووجود النوع الثاني ليس ترفًا: أغلب محتوى الموقع بطاقاتٌ متكرّرة، ولو
 * فُكّت إلى نصوص مفردة لَما استطاع أحد **إضافة بطاقة أو حذفها** — وهو
 * أول ما يُطلب حين يتغيّر العرض. تحريرُ النصّ وحده يجمّد البنية.
 *
 * وقاعدة هذا الملف: **لا مدخل هنا إلا وهو مقروء في صفحة**. مدخلٌ مسجّل
 * لا يقرؤه أحد أسوأ من غياب المدخل، لأن المحرِّرة تراه في اللوحة فتعدّله
 * وتحفظه ثم لا يتغيّر شيء على الموقع — فتفقد ثقتها بالمحرِّر كله. وقد
 * وقع هذا فعلًا في أول نسخة (سُجّلت `security.controls` ولم تُقرأ)،
 * فصار اختبارٌ آليّ يمنع تكراره.
 *
 * وإضافة محتوى جديد إلى التحرير خطوتان: أضف مدخلًا هنا، واقرأه في
 * الصفحة عبر `t()` أو `t.list()`. لا تعديل في المحرِّر ولا في قاعدة
 * البيانات.
 *
 * أما الأيقونات فليست محتوى: تبقى في الشيفرة وتُختار بترتيب العنصر في
 * قائمته. لأن اختيار أيقونة من ألف أيقونة ليس تحريرًا بل تصميمًا، وفتحُه
 * في اللوحة يُنتج صفحات متنافرة أسرع مما يُنتج صفحات أجمل.
 */

export interface SiteTextEntry {
  kind: 'text';
  page: string;
  label: string;
  value: string;
  multiline?: boolean;
  hint?: string;
}

export interface SiteListField {
  name: string;
  label: string;
  multiline?: boolean;
  /** `toggle` يُعرض مربّع اختيار ويُخزَّن «نعم» أو فراغًا */
  type?: 'text' | 'toggle';
  hint?: string;
}

export interface SiteListEntry {
  kind: 'list';
  page: string;
  label: string;
  hint?: string;
  /** حقول كل عنصر — تُبنى منها صفوف المحرِّر */
  fields: SiteListField[];
  value: Record<string, string>[];
}

export type SiteEntry = SiteTextEntry | SiteListEntry;

