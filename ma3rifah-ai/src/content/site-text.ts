/** القيم الافتراضية جاهزةً للدمج — النصّ كما هو، والقائمة مُسلسَلة */
export function defaultSiteText(): Record<string, string> {
  const out: Record<string, string> = {};
  for (const [key, entry] of Object.entries(SITE_TEXT)) {
    out[key] = entry.kind === 'list' ? JSON.stringify(entry.value) : entry.value;
  }
  return out;
}
