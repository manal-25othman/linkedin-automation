/** فهرس بالمقالات مرتّبًا بأقسامه */
export function helpByCategory(): { category: string; articles: HelpArticle[] }[] {
  return HELP_CATEGORIES.map((category) => ({
    category,
    articles: HELP_ARTICLES.filter((article) => article.category === category),
  })).filter((group) => group.articles.length > 0);
}

export function findHelpArticle(slug: string): HelpArticle | null {
  return HELP_ARTICLES.find((article) => article.slug === slug) ?? null;
}

/**
 * بحث نصّي بسيط.
 *
 * يُطابق العنوان والملخّص والكلمات المفتاحية والمتن، ويرتّب بأهمية
 * موضع التطابق: عنوانٌ يطابق أدلّ من كلمة وردت في وسط مقال.
 *
 * ولا يُستعمل محرّك بحث: ثلاثة عشر مقالًا تُفحص كلها في أقل من ملّي
 * ثانية، وإدخالُ مكتبة لأجلها ثمنٌ بلا مقابل.
 */
export function searchHelp(query: string): HelpArticle[] {
  const needle = query.trim().toLowerCase();
  if (needle === '') return [];

  const scored = HELP_ARTICLES.map((article) => {
    let score = 0;
    if (article.title.toLowerCase().includes(needle)) score += 10;
    if (article.summary.toLowerCase().includes(needle)) score += 5;
    if (article.keywords?.some((word) => word.toLowerCase().includes(needle))) score += 5;
    if (article.body.toLowerCase().includes(needle)) score += 1;
    return { article, score };
  }).filter((entry) => entry.score > 0);

  scored.sort((a, b) => b.score - a.score);
  return scored.map((entry) => entry.article);
}
