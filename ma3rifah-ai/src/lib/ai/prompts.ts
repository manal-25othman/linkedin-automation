/**
 * الصيغة التي يستخدمها النموذج عند غياب المعلومة.
 * تُطابَق نصًا لتحديد الإجابات غير المُجابة وتسجيلها كفجوة معرفة.
 */
export const NO_ANSWER_MARKER = 'لم أجد معلومات كافية في قاعدة معرفة الشركة';

const NO_ANSWER_PATTERNS = [
  NO_ANSWER_MARKER,
  'لم أجد معلومات كافية',
  'لا توجد معلومات كافية',
  'لم أعثر على معلومات',
  "couldn't find enough information",
  'could not find enough information',
  'no sufficient information',
];

export function isUnansweredResponse(answer: string): boolean {
  const normalized = answer.toLowerCase();
  return NO_ANSWER_PATTERNS.some((pattern) => normalized.includes(pattern.toLowerCase()));
}
