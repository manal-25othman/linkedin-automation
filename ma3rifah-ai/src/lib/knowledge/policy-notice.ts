/**
 * تنبيه المسوّدة، وما يحلّ محلّه عند الاعتماد.
 *
 * العطل الذي أنشأ هذا الملف: التنبيه يُذيَّل بالمسوّدة برمجيًّا —
 * وهذا صحيح — ثم **يُنشر معها كما هو**. فتدخل قاعدةَ المعرفة سياسةٌ
 * اعتمدتها الإدارة ونصُّها يقول عن نفسه إنه «مسودة… تحتاج مراجعة
 * مختص قبل اعتمادها ملزِمة».
 *
 * وليس هذا سطرًا زائدًا في الهامش: النصّ يُقطَّع ويُفهرس كبقية
 * المستند، فيُسترجع ويظهر للموظف في مقتطف المصدر — وقد يُطابق سؤالًا
 * مثل «هل هذه السياسة ملزمة؟» فيُجاب بأنها ليست كذلك، عن سياسةٍ
 * اعتمدتها الشركة.
 *
 * فالتنبيه صحيح في موضعه وكاذب في الموضع التالي له. وعلاجه ليس حذفه:
 * «أُعدّت بمساعدة المنصّة» أثرٌ يلزم بقاؤه في متن ما يقرأه الموظف، لا
 * في سجلٍّ إداري وحده. فيُستبدل بتنبيهٍ صادقٍ عن الحالة الجديدة.
 *
 * وهذا الملف صغير ومنفصل عمدًا: يستورده المولِّد والناشر معًا، ولو
 * عاش في أحدهما لاستورد الآخرُ معه نصفَ الميزة.
 */

/** يُذيَّل بكل مسوّدة وقت التوليد */
export const POLICY_LEGAL_NOTICE =
  'مسودة تنظيمية أُعدّت بمساعدة المنصة استنادًا إلى وثائق الشركة والمراجع ' +
  'النظامية المذكورة. تحتاج مراجعة مختص قبل اعتمادها ملزِمة.';

/**
 * ما يميّز سطر التنبيه حين يُبحث عنه في نصٍّ حرّره المدير.
 *
 * ولا يُطابَق التنبيه كاملًا: المدير يحرّر المتن في مربّع نصّ، وقد
 * يمسّ السطر بحرف. والمطابقة على عبارةٍ قصيرة دالّة أمتن — وإخفاقها
 * لا يُسقط شيئًا، إذ يُلحق تنبيه الاعتماد على كل حال.
 */
const DRAFT_NOTICE_HINT = 'مسودة تنظيمية';

/** عبارة تنبيه الاعتماد — تُنزع هي أيضًا كيلا تتراكم عند إعادة النشر */
const APPROVED_NOTICE_HINT = 'اعتمدتها إدارة الشركة بتاريخ';

/**
 * السطر الذي يحمل أحد التنبيهين، مع الفاصل الذي يسبقه إن وُجد.
 *
 * و`\n*` لا `\n+`: السطر قد يكون أول المتن إن نقله المدير إلى أعلاه،
 * وقاعدةٌ لا تمسك أول سطرٍ في النصّ تمسك كل شيء إلا الحالة التي
 * يحرّرها إنسان.
 */
const NOTICE_BLOCK = new RegExp(
  `(?:\\n*-{3,})?\\n*>?[^\\n]*(?:${DRAFT_NOTICE_HINT}|${APPROVED_NOTICE_HINT})[^\\n]*`,
  'g',
);

/**
 * صيغة التاريخ داخل متن السياسة.
 *
 * بالتقويم الميلادي صراحةً وبتوقيت الرياض: المتن **لقطةٌ ثابتة** تُقرأ
 * بعد سنة، فلا يُترك تقويمها لإعداد المتصفّح ولا لمنطقة الخادم. وبلا
 * `ca-gregory` يُخرج `ar-SA` تاريخًا هجريًّا في بعض البيئات دون بعض،
 * فيختلف نصّ السياسة باختلاف مكان تشغيل الخادم — وهو أسوأ اختلافٍ
 * يقع في وثيقةٍ ملزِمة.
 */
function formatApprovalDate(at: Date): string {
  try {
    return new Intl.DateTimeFormat('ar-SA-u-ca-gregory', {
      timeZone: 'Asia/Riyadh',
      year: 'numeric',
      month: 'long',
      day: 'numeric',
    }).format(at);
  } catch {
    // بيئة بلا بيانات مناطق زمنية — التاريخ أهمّ من شكله
    return at.toISOString().slice(0, 10);
  }
}

export function approvedPolicyNotice(at: Date): string {
  return (
    `سياسة داخلية اعتمدتها إدارة الشركة بتاريخ ${formatApprovalDate(at)}. ` +
    'أُعدّت بمساعدة المنصة استنادًا إلى وثائق الشركة والمراجع النظامية المذكورة.'
  );
}

/** هل ما زال نصُّ المسوّدة يصف نفسه مسوّدةً؟ — يُستعمل في الحراسة والاختبار */
export function mentionsDraftNotice(body: string): boolean {
  return body.includes(DRAFT_NOTICE_HINT);
}

/**
 * تحويل متن المسوّدة إلى متن سياسة معتمدة.
 *
 * يُنزع سطر تنبيه المسوّدة أينما وقع — لا من آخر النصّ وحده، فالمدير
 * يحرّر ويُحرّك — ثم يُلحق تنبيه الاعتماد مرةً واحدة في آخره.
 */
export function finalizePolicyBody(body: string, approvedAt: Date): string {
  const stripped = body.replace(NOTICE_BLOCK, '').trim();
  return `${stripped}\n\n---\n\n> ${approvedPolicyNotice(approvedAt)}`;
}
