/**
 * فلتر ضجيج فجوات المعرفة.
 *
 * كل سؤال بلا جواب يُسجَّل فجوةً — وهذا صحيح للأسئلة الحقيقية. لكن
 * المستخدم يكتب في المحادثة ما ليس سؤالًا أصلًا: «تاكد الان»، «هل
 * حصلت على الاجابه»، «طيب كمل». فيفشل استرجاعها بالطبع، وتُسجَّل
 * فجوات، فتمتلئ قائمة المدير بما لا يُوثَّق ولا يُجاب — والقائمة
 * المضجّة تُهمَل كلها، ومعها الفجوات الحقيقية.
 *
 * الفلتر متحفّظ عمدًا، وكل نمطٍ فيه مقيَّد بحدود الكلمة أو ببداية
 * النصّ حتى لا يصيب سؤالًا حقيقيًا يشاركه لفظًا: «كيف أتأكد من
 * استحقاق الإجازة؟» سؤال معرفة يمرّ، و«تاكد الان» متابعةٌ تُستبعد.
 * والخطأ الأهون هنا فجوةُ ضجيجٍ زائدة، لا سؤالٌ حقيقيّ ضائع.
 */

/** فوق هذا الطول يُعامَل النص سؤالًا مهما بدا شكله */
const MAX_META_LENGTH = 60;

/** أنماطٌ من أسئلة إنتاج حقيقية سُجِّلت فجواتٍ وليست أسئلة */
const META_PATTERNS: readonly RegExp[] = [
  // أمرُ تحقّقٍ موجَّه للمساعد — كلمة مستقلة، فلا يصيب «أتأكد» و«التحقق»
  /(^|\s)(تا?أ?كد|تحقق)(\s|$)/,
  // سؤال عن إجابة المحادثة نفسها لا عن المعرفة
  /هل (حصلت|وصلت) على (ال)?[إا]جاب/,
  /هل (انت|أنت) متأ?اكد/,
  // مجاملات وتصريف حديث في أول النص
  /^(طيب|تمام|ممتاز|شكرا|مشكور|اوك|ok|اها|ايوه)(\s|$)/i,
  // أوامر إكمال في أول النص
  /^(كمل|واصل|زد|وضح|وضّح|أعد الصياغة|اعد الصياغة)(\s|$)/,
];

/** هل النصّ متابعة محادثية لا سؤال معرفة؟ */
export function isConversationalFollowUp(question: string): boolean {
  const trimmed = question.trim();
  if (trimmed.length > MAX_META_LENGTH) return false;
  return META_PATTERNS.some((pattern) => pattern.test(trimmed));
}
